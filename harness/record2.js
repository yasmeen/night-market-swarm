const { open } = require('./common');
const fs = require('fs');
(async () => {
  const dir = '/home/claude/agenthq/harness/video';
  fs.rmSync(dir, { recursive: true, force: true }); fs.mkdirSync(dir);
  const t = await open({ swarm: 'big' });
  const p = t.page, w = ms => p.waitForTimeout(ms);
  const cdp = await t.ctx.newCDPSession(p); const frames = [];
  cdp.on('Page.screencastFrame', f => { frames.push(f.metadata.timestamp); fs.writeFileSync(dir + '/f' + String(frames.length - 1).padStart(5, '0') + '.png', Buffer.from(f.data, 'base64')); cdp.send('Page.screencastFrameAck', { sessionId: f.sessionId }).catch(() => {}); });
  await cdp.send('Page.startScreencast', { format: 'png', everyNthFrame: 2 });
  const stall = async name => { const b = await p.locator('.stall', { hasText: name }).first().boundingBox(); await p.mouse.click(b.x + b.width / 2, b.y + b.height * 0.75); };
  const done = (i, at) => p.evaluate(([i, at]) => __push('big', 'backlog-d' + i, { stall: 'backlog', worker: 'w' + (i % 8 + 1), unit: 'pr-' + i, done: true, at, text: 'PR ' + (101 + i) + ' reviewed. Safe to merge.' }), [i, at]);
  await w(700);
  await p.evaluate(() => __push('big', 'code-02', { stall: 'code', at: '2026-11-01T00:15:00Z', text: 'Tests pass. Opening the pull request.' }));
  await w(900);
  await stall('Backlog'); await w(3600);
  await done(9, '2026-11-01T00:16:00Z'); await w(1100);
  await done(10, '2026-11-01T00:17:00Z'); await w(1100);
  await done(11, '2026-11-01T00:18:00Z'); await w(1500);
  await p.screenshot({ path: '/home/claude/agenthq/assets/d1.png' });
  await p.keyboard.press('Escape'); await p.mouse.move(1150, 20); await w(300);
  await p.keyboard.down('ArrowRight'); await w(1700); await p.keyboard.up('ArrowRight');
  await p.keyboard.down('ArrowDown'); await w(1500); await p.keyboard.up('ArrowDown');
  await w(300);
  await p.evaluate(() => __stall('big', 'legal', { name: 'Legal', order: 11, role: 'Contract reader', model: 'Opus 5.5', status: 'working', statusAt: '2026-11-01T00:00:00Z', task: 'Read the vendor terms for anything risky.', look: { awning: ['#2f6f5e', '#f6e7c8'], panel: '#2f6f5e', goods: 'boba', acc: ['glasses'] } }));
  await w(900);
  await p.evaluate(() => __stall('big', 'pricing', { name: 'Pricing', order: 12, role: 'Analyst', model: 'Sonnet 5.5', status: 'working', statusAt: '2026-11-01T00:00:00Z', task: 'Model three price points.' }));
  await w(1200);
  await p.evaluate(() => __push('big', 'legal-01', { stall: 'legal', at: '2026-11-01T00:20:00Z', text: 'Two clauses need a second look.' }));
  await stall('Legal'); await w(3200);
  await p.screenshot({ path: '/home/claude/agenthq/assets/d2.png' });
  await p.keyboard.press('Escape'); await p.mouse.move(1150, 20); await w(300);
  await p.click('#zoom'); await p.mouse.move(1150, 20); await w(2200);
  await p.screenshot({ path: '/home/claude/agenthq/assets/d3.png' });
  await cdp.send('Page.stopScreencast');
  let list = '';
  for (let i = 0; i < frames.length; i++) list += `file 'f${String(i).padStart(5, '0')}.png'\nduration ${(i + 1 < frames.length ? frames[i + 1] - frames[i] : 0.08).toFixed(4)}\n`;
  fs.writeFileSync(dir + '/list.txt', list);
  console.log('frames', frames.length, 'secs', (frames[frames.length - 1] - frames[0]).toFixed(1), 'errors', t.errs);
  await t.close();
})();
